/* ------------------------------- height/width related --------------------------------- */
export const setHW = (h, w) => {
    return {
        height: h,
        width: w
    }
};


export const setHwInPercent = (h, w) => {
    return {
        height: `${h}%`,
        width: `${w}%`
    }
}

export const setHwWrtWindow = (h, w) => {
    return {
        height: `${h}vh`,
        width: `${w}vw`
    }
}

export const setHWrtWindow = (h) => {
    return {
        height: `${h}vh`,
    }
}

export const setWWrtWindow = (w) => {
    return {
        width: `${w}vw`
    }
}
